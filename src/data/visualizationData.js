// ==================== MATHEMATICAL MODELS ====================
export const ECOLOGICAL_MODELS = {
  logisticGrowth: (N, r, K, T, R, P) => {
    const tempFactor = Math.exp(-0.5 * Math.pow((T - 25) / 10, 2));
    const rainFactor = Math.min(1, R / 100);
    const pollutionFactor = Math.exp(-P / 50);
    const effectiveR = r * tempFactor * rainFactor * pollutionFactor;
    return N + effectiveR * N * (1 - N / K);
  },

  predatorPrey: (prey, pred, a, b, c, d, refugia = 0.1) => {
    const preyRefuge = prey * refugia;
    const availablePrey = Math.max(0, prey - preyRefuge);
    const newPrey = prey + (a * prey - b * availablePrey * pred);
    const newPred = pred + (c * availablePrey * pred - d * pred);
    return [Math.max(newPrey, 0), Math.max(newPred, 0)];
  },

  competition: (N1, N2, r1, r2, K1, K2, alpha, beta) => {
    const dN1 = r1 * N1 * (1 - (N1 + alpha * N2) / K1);
    const dN2 = r2 * N2 * (1 - (N2 + beta * N1) / K2);
    return [N1 + dN1, N2 + dN2];
  },

  stabilityIndex: (data) => {
    if (data.length < 10) return 0.5;
    const values = data.map(d => d.pop || d.prey || d.producers || 0);
    const mean = values.reduce((a, b) => a + b, 0) / values.length;
    const variance = values.reduce((a, b) => a + Math.pow(b - mean, 2), 0) / values.length;
    const cv = Math.sqrt(variance) / mean;
    return Math.max(0, Math.min(1, 1 - cv));
  },

  biodiversityIndex: (species, evenness = 0.8) => {
    const richness = Math.min(1, species / 1000);
    return richness * evenness;
  },

  carbonSequestration: (forestArea, forestType = 'tropical') => {
    const rates = { tropical: 12.5, temperate: 7.5, boreal: 5.0 };
    return forestArea * (rates[forestType] || 10) * 1000;
  }
};

